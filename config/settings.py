def _env_bool(name: str, default: bool) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    if value.strip().lower() in {"1", "true", "yes", "on"}:
        return True
    if value.strip().lower() in {"0", "false", "no", "off"}:
        return False
    raise ImproperlyConfigured(f"{name} must be a boolean value.")


def _host_list(value: str | None) -> list[str]:
    return [host.strip() for host in (value or "").split(",") if host.strip()]


def _allowed_hosts() -> list[str]:
    """Combine explicit hosts with the hostname supplied by Vercel."""
    values = _host_list(os.getenv("ALLOWED_HOSTS"))
    for variable in (
        "VERCEL_URL",
        "VERCEL_PROJECT_PRODUCTION_URL",
        "VERCEL_BRANCH_URL",
    ):
        values.extend(_host_list(os.getenv(variable)))
    return list(dict.fromkeys(values))


def _vercel_hosts() -> list[str]:
    hosts = []
    for variable in (
        "VERCEL_URL",
        "VERCEL_PROJECT_PRODUCTION_URL",
        "VERCEL_BRANCH_URL",
    ):
        hosts.extend(_host_list(os.getenv(variable)))
    return list(dict.fromkeys(hosts))


def _csrf_trusted_origins() -> list[str]:
    origins = _host_list(os.getenv("CSRF_TRUSTED_ORIGINS"))
    for host in _vercel_hosts():
        origins.append(host if "://" in host else f"https://{host}")
    return list(dict.fromkeys(origins))


